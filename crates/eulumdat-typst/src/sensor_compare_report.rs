//! Sensor comparison report: two sensors under the same conditions (plan,
//! polar and cartesian overlays, numbers with Δ %, range over the mounting
//! height, room check). Typst source with inline SVG, like the sensor report.

use crate::sensor_report::{esc, image, table};
use eulumdat::diagram::SvgTheme;
use eulumdat::sensor::compare::{
    cartesian_overlay_svg, height_chart_svg, plan_overlay_svg, polar_overlay_svg, room_check,
    CompareConditions, HeightChartLabels, RoomCheck, SensorComparison, SideValues,
};
use eulumdat::sensor::coverage::{CoverageRoom, DEFAULT_WALL_MARGIN};
use eulumdat::sensor::en15193::{OccupancyControl, SpaceType};
use eulumdat::sensor::{Motion, Quality, SensorFile};

/// The room of the room check.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CompareRoom {
    pub length: f64,
    pub width: f64,
    /// Motion type the sensors are planned for.
    pub motion: Motion,
    /// EN 15193-1 control and space type, hold time ≤ 15 min.
    pub control: OccupancyControl,
    pub space: SpaceType,
    pub hold_ok: bool,
    /// Price per sensor (any currency), for the cost line.
    pub price: Option<f64>,
}

/// Report settings.
#[derive(Debug, Clone)]
pub struct SensorCompareOptions {
    pub label_a: String,
    pub label_b: String,
    pub conditions: CompareConditions,
    /// C-plane of the polar / cartesian overlays and the cut on the plan.
    pub c_plane: f64,
    /// Motion type of the polar / cartesian overlays.
    pub motion: Motion,
    /// Mounting heights of the range chart (m).
    pub heights: (f64, f64),
    pub room: Option<CompareRoom>,
    /// Date printed on the report (the caller's clock).
    pub date: String,
    /// Either side is a synthetic demo sensor.
    pub demo: bool,
}

fn quality(q: Option<Quality>) -> &'static str {
    match q {
        Some(Quality::Measured) | None => "",
        Some(Quality::Interpolated) => " (i)",
        Some(Quality::Extrapolated) => " (e)",
    }
}

fn val(v: Option<SideValues>, f: fn(&SideValues) -> f64, unit: &str) -> String {
    match v {
        Some(x) if x.detected => format!("{:.2} {unit}{}", f(&x), quality(x.quality)),
        Some(_) => "not detected".into(),
        None => "no data".into(),
    }
}

fn pct(d: Option<f64>) -> String {
    d.map(|d| format!("{d:+.0} %"))
        .unwrap_or_else(|| "–".into())
}

fn kind(f: &SensorFile) -> &'static str {
    f.kind_label()
}

/// Typst source of the comparison report.
pub fn generate_sensor_comparison_report(
    a: &SensorFile,
    b: &SensorFile,
    opt: &SensorCompareOptions,
) -> String {
    let theme = SvgTheme::light();
    let c = &opt.conditions;
    let (la, lb) = (esc(&opt.label_a), esc(&opt.label_b));
    let mut s = String::with_capacity(160 * 1024);
    s.push_str(&format!(
        r##"// Sensor comparison report, generated by eulumdat-typst
#set document(title: "Sensor comparison", author: "Candelabra · eulumdat-rs")
#set page(paper: "a4", margin: (x: 2cm, y: 2.2cm),
  header: context {{ if counter(page).get().first() > 1 [#set text(size: 9pt, fill: gray); Sensor comparison #h(1fr) #counter(page).display()] }},
  footer: context [#set text(size: 8pt, fill: gray); #h(1fr) Generated with Candelabra (iesna.eu) and eulumdat-rs])
#set text(size: 10pt)
#set heading(numbering: "1.")

#align(center)[
  #text(size: 20pt, weight: "bold")[Sensor comparison] \
  #v(2pt)
  #text(size: 12pt)[A: {la}] \
  #text(size: 12pt)[B: {lb}] \
  #v(2pt)
  #text(size: 9pt, fill: gray)[{ka} · {kb}{date}]
]
#v(8pt)
"##,
        ka = kind(a),
        kb = kind(b),
        date = if opt.date.is_empty() {
            String::new()
        } else {
            format!(" · {}", esc(&opt.date))
        }
    ));
    if opt.demo {
        s.push_str("#align(center)[#text(fill: rgb(\"#b45309\"))[Contains synthetic demo data, not products.]]\n#v(4pt)\n");
    }

    // 1. Conditions and numbers
    s.push_str("= Same conditions, side by side\n");
    s.push_str(&format!(
        "Sensors at *{:.2} m*; walking evaluated on the floor ({:.2} m), seated presence on the workplane ({:.2} m){}. A sensor LDT is cut at mounting height − plane, a SensXML file is read at its mounting height.\n\n",
        c.mount,
        c.walk_plane,
        c.presence_plane,
        if c.planning { "; SensXML idealised planning shapes" } else { "" }
    ));
    let cmp = SensorComparison::new(a, b, c, &opt.label_a, &opt.label_b);
    let rows: Vec<Vec<String>> = cmp
        .rows
        .iter()
        .map(|r| {
            vec![
                r.motion.label().to_string(),
                format!("{:.2} m", r.plane),
                val(r.a, |x| x.max_range, "m"),
                val(r.b, |x| x.max_range, "m"),
                pct(r.delta_pct(|x| x.max_range)),
                val(r.a, |x| x.area_m2, "m²"),
                val(r.b, |x| x.area_m2, "m²"),
                pct(r.delta_pct(|x| x.area_m2)),
            ]
        })
        .collect();
    s.push_str(&table(
        "(auto, auto, 1fr, 1fr, auto, 1fr, 1fr, auto)",
        &[
            "Motion", "Plane", "A range", "B range", "Δ", "A area", "B area", "Δ",
        ],
        &rows,
    ));
    s.push_str("#text(size: 8pt)[Δ = (B − A) / A. (i) interpolated, (e) extrapolated between / beyond the measured heights of a SensXML file.]\n\n");
    for (tag, f) in [("A", a), ("B", b)] {
        for w in f.warnings() {
            s.push_str(&format!("_{tag}: {}_\n\n", esc(&w.message())));
        }
    }

    // 2. Plan overlay
    s.push_str("= Detection areas\n");
    s.push_str(&format!(
        "A filled, B dashed; dashed line: the C{:.0} cut of the polar view, with the reach of both sensors on it.\n\n",
        opt.c_plane
    ));
    let plan = plan_overlay_svg(
        a,
        b,
        c,
        &Motion::ALL,
        460.0,
        &theme,
        &|m| m.label().to_string(),
        Some(opt.c_plane),
    );
    s.push_str(&image(&plan, 70));

    // 3. Polar and cartesian overlays
    s.push_str(&format!(
        "#pagebreak()\n= Detection volume at C{:.0} – C{:.0} ({})\n",
        opt.c_plane,
        (opt.c_plane + 180.0) % 360.0,
        opt.motion.label()
    ));
    match polar_overlay_svg(
        a,
        b,
        opt.motion,
        c.planning,
        opt.c_plane,
        460.0,
        &theme,
        &opt.label_a,
        &opt.label_b,
    ) {
        Some(svg) => s.push_str(&image(&svg, 62)),
        None => s.push_str("_One of the sensors has no data for this motion type._\n\n"),
    }
    if let Some(svg) = cartesian_overlay_svg(
        a,
        b,
        opt.motion,
        c.planning,
        opt.c_plane,
        600.0,
        360.0,
        &theme,
        &opt.label_a,
        &opt.label_b,
    ) {
        s.push_str(&image(&svg, 85));
    }
    s.push_str("#text(size: 8pt)[Ranges in metres from the sensor to the boundary of the detection volume (SensXML: volume rebuilt from the measured heights).]\n\n");

    // 4. Range over the mounting height
    s.push_str("#pagebreak()\n= Range over the mounting height\n");
    s.push_str("Diameter of the circle with the same area as the detection area. A solid, B dashed; circles: measured heights of a SensXML file; a gap: not detected at that height.\n\n");
    let chart = height_chart_svg(
        a,
        b,
        c,
        &Motion::ALL,
        opt.heights,
        640.0,
        380.0,
        &theme,
        &HeightChartLabels::default(),
        &|m| m.label().to_string(),
        &opt.label_a,
        &opt.label_b,
    );
    s.push_str(&image(&chart, 92));

    // 5. Room check
    if let Some(room) = opt.room {
        let cr = CoverageRoom {
            length: room.length,
            width: room.width,
            mount_height: c.mount,
            walk_plane: c.walk_plane,
            presence_plane: c.presence_plane,
            margin: DEFAULT_WALL_MARGIN,
        };
        s.push_str(&format!(
            "= Room check: {:.1} × {:.1} m, sensors at {:.2} m\n",
            room.length, room.width, c.mount
        ));
        s.push_str(&format!(
            "Fewest sensors on a regular grid that detect ≥ 95 % of the room for {} (wall margin {DEFAULT_WALL_MARGIN} m; both orientations tried). EN 15193-1: {}, {}.\n\n",
            room.motion.label().to_lowercase(),
            room.control.label(),
            room.space.label()
        ));
        let ctl = Some((room.control, room.space, room.hold_ok));
        let ra = room_check(a, &cr, c.planning, room.motion, 100, ctl);
        let rb = room_check(b, &cr, c.planning, room.motion, 100, ctl);
        let col = |r: &Option<RoomCheck>| -> Vec<String> {
            match r {
                None => vec!["not detected".into(); 6],
                Some(r) => vec![
                    format!(
                        "{} ({} × {}{})",
                        r.count,
                        r.nx,
                        r.ny,
                        if r.rotation != 0.0 {
                            ", turned 90°"
                        } else {
                            ""
                        }
                    ) + if r.reached {
                        ""
                    } else {
                        " (target not reached)"
                    },
                    format!("{:.1} %", r.covered * 100.0),
                    format!("{:.1} %", r.overlap * 100.0),
                    format!("{:.1} m²", r.m2_per_sensor),
                    r.fo.map(|f| {
                        format!(
                            "{:.2}{}",
                            f.f_o,
                            if f.credited { "" } else { " (no credit)" }
                        )
                    })
                    .unwrap_or_default(),
                    match room.price {
                        Some(p) => format!("{:.0}", p * r.count as f64),
                        None => "–".into(),
                    },
                ],
            }
        };
        let (ca, cb) = (col(&ra), col(&rb));
        let labels = [
            "Sensors",
            "Covered",
            "Overlap",
            "Floor area per sensor",
            "F_O (EN 15193-1)",
            "Cost",
        ];
        let rows: Vec<Vec<String>> = labels
            .iter()
            .enumerate()
            .map(|(i, l)| vec![l.to_string(), ca[i].clone(), cb[i].clone()])
            .collect();
        s.push_str(&table(
            "(auto, 1fr, 1fr)",
            &[
                "",
                &format!("A: {}", opt.label_a),
                &format!("B: {}", opt.label_b),
            ],
            &rows,
        ));
    }

    s.push_str("\n= Method\n#text(size: 9pt)[Both sensors are read under the same conditions: a sensor LDT (detection volume in metres) is cut at mounting height − detection plane, with the motion types scaled by the parameters in lines 33–42; a SensXML file gives the area measured (or interpolated / extrapolated) at the mounting height. Areas are compared by size and shape only; data quality and test conditions of the sources may differ. The room check uses an automatic grid that reaches ≥ 95 % of the evaluated area, one control group per sensor for EN 15193-1 Annex E.]\n");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn report_has_all_sections() {
        let a = SensorFile::from_bytes(
            include_bytes!("../../eulumdat/tests/fixtures/sensors/demo_ceiling_360.ldt"),
            "sensor/sensldt",
        )
        .unwrap();
        let b = SensorFile::from_bytes(
            include_bytes!("../../eulumdat/tests/fixtures/sensors/demo_ceiling_sensxml.xml"),
            "",
        )
        .unwrap();
        let opt = SensorCompareOptions {
            label_a: "Demo LDT".into(),
            label_b: "Demo SensXML".into(),
            conditions: CompareConditions::default(),
            c_plane: 90.0,
            motion: Motion::Tangential,
            heights: (2.0, 8.0),
            room: Some(CompareRoom {
                length: 10.0,
                width: 8.0,
                motion: Motion::Presence,
                control: OccupancyControl::AutoOnAutoOff,
                space: SpaceType::Classroom,
                hold_ok: true,
                price: Some(120.0),
            }),
            date: "2026-11-06".into(),
            demo: true,
        };
        let t = generate_sensor_comparison_report(&a, &b, &opt);
        for h in [
            "= Same conditions",
            "= Detection areas",
            "= Detection volume at C90",
            "= Range over the mounting height",
            "= Room check",
            "= Method",
        ] {
            assert!(t.contains(h), "{h}");
        }
        assert!(t.matches("#image(bytes(").count() >= 4);
    }
}
