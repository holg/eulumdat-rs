//! Typst report for a presence / motion sensor (sensor LDT or SensXML).
//!
//! The source is self-contained (diagrams are inline SVG), so the same text
//! compiles with the `typst` CLI, the in-browser Typst WASM, or the
//! `compile` feature.

use eulumdat::diagram::SvgTheme;
use eulumdat::sensor::{
    diagrams, DetectionVolume, Footprint, Motion, MountingHint, Quality, SensXml, SensorDiagram,
    SensorPlanSvg, SensorPlanTrace, TRACE_COLORS,
};

/// The sensor a report is about.
pub enum SensorSource<'a> {
    /// Sensor LDT: the detection volume in metres.
    Ldt(&'a DetectionVolume),
    /// SensXML: detection areas per mounting height.
    Xml(&'a SensXml),
}

/// Report settings.
#[derive(Debug, Clone)]
pub struct SensorReportOptions {
    /// Title line (file or product name).
    pub name: String,
    /// Height for the plan view: depth below the sensor (sensor LDT) or
    /// mounting height (SensXML), in m.
    pub height: f64,
    /// SensXML: idealised planning shapes instead of the measured data.
    pub planning: bool,
    /// Date printed on the report (the caller's clock; no system time here).
    pub date: String,
    /// The data is a synthetic demo, not a product.
    pub demo: bool,
}

impl Default for SensorReportOptions {
    fn default() -> Self {
        Self {
            name: "Sensor".into(),
            height: eulumdat::sensor::REFERENCE_DEPTH,
            planning: false,
            date: String::new(),
            demo: false,
        }
    }
}

/// Today's date (local clock) for [`SensorReportOptions::date`].
pub fn today() -> String {
    chrono::Local::now().format("%Y-%m-%d").to_string()
}

pub(crate) fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if matches!(
            c,
            '\\' | '"' | '#' | '$' | '*' | '_' | '@' | '<' | '>' | '[' | ']' | '`' | '~'
        ) {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

pub(crate) fn image(svg: &str, width_pct: u32) -> String {
    format!(
        "#align(center)[#image(bytes(\"{}\"), width: {width_pct}%)]\n",
        svg.replace('\\', "\\\\").replace('"', "\\\"")
    )
}

fn cell(s: &str) -> String {
    format!("[{}]", esc(s))
}

fn bold_cell(s: &str) -> String {
    format!("[*{}*]", esc(s))
}

pub(crate) fn table(columns: &str, header: &[&str], rows: &[Vec<String>]) -> String {
    let mut t = format!(
        "#table(columns: {columns}, inset: 5pt, stroke: 0.4pt + luma(170), fill: (x, y) => if y == 0 {{ luma(235) }},\n"
    );
    t.push_str(
        &header
            .iter()
            .map(|h| bold_cell(h))
            .collect::<Vec<_>>()
            .join(", "),
    );
    for r in rows {
        t.push_str(",\n");
        t.push_str(&r.iter().map(|c| cell(c)).collect::<Vec<_>>().join(", "));
    }
    t.push_str(")\n");
    t
}

fn quality_mark(q: Option<Quality>) -> &'static str {
    match q {
        Some(Quality::Interpolated) => " (i)",
        Some(Quality::Extrapolated) => " (e)",
        _ => "",
    }
}

/// Footprint of one motion type at one height, with its data quality.
fn footprint(
    src: &SensorSource,
    m: Motion,
    h: f64,
    planning: bool,
) -> Option<(Footprint, Option<Quality>)> {
    match src {
        SensorSource::Ldt(v) => v.motion_footprint(m, h, 1.0).map(|f| (f, None)),
        SensorSource::Xml(x) => x.footprint(m, h, planning).map(|(f, q)| (f, Some(q))),
    }
}

/// The whole Typst source of a sensor report.
pub fn generate_sensor_report(src: &SensorSource, opt: &SensorReportOptions) -> String {
    let name = esc(&opt.name);
    let kind = kind_label(src);
    let mut s = String::with_capacity(96 * 1024);
    s.push_str(&format!(
        r##"// Sensor report, generated by eulumdat-typst
#set document(title: "Sensor report: {name}", author: "Candelabra · eulumdat-rs")
#set page(paper: "a4", margin: (x: 2cm, y: 2.2cm),
  header: context {{ if counter(page).get().first() > 1 [#set text(size: 9pt, fill: gray); Sensor report · {name} #h(1fr) #counter(page).display()] }},
  footer: context [#set text(size: 8pt, fill: gray); #h(1fr) Generated with Candelabra (iesna.eu) and eulumdat-rs])
#set text(size: 10pt)
#set heading(numbering: "1.")

#align(center)[
  #text(size: 20pt, weight: "bold")[Sensor report] \
  #v(2pt)
  #text(size: 13pt)[{name}] \
  #v(2pt)
  #text(size: 9pt, fill: gray)[{kind}{date}]
]
#v(8pt)
"##,
        date = if opt.date.is_empty() {
            String::new()
        } else {
            format!(" · {}", esc(&opt.date))
        }
    ));
    if opt.demo {
        s.push_str("#align(center)[#text(fill: rgb(\"#b45309\"))[Synthetic demo data, not a product.]]\n#v(4pt)\n");
    }

    s.push_str(&report_body(src, opt));
    s
}

/// Report sections (summary, areas, height table, volume, method) with
/// top-level headings, shared by the stand-alone report and the chapter.
fn report_body(src: &SensorSource, opt: &SensorReportOptions) -> String {
    let theme = diagrams::sensor_theme(&SvgTheme::light());
    let h = opt.height;
    let mut s = String::with_capacity(96 * 1024);
    // 1. Summary
    s.push_str("= Summary\n");
    let mut rows: Vec<Vec<String>> = Vec::new();
    match src {
        SensorSource::Ldt(v) => {
            let l = v.ldt();
            let p = v.params();
            if !l.identification.trim().is_empty() {
                rows.push(vec!["Manufacturer".into(), l.identification.trim().into()]);
            }
            rows.push(vec!["Product".into(), l.luminaire_name.trim().into()]);
            if !l.luminaire_number.trim().is_empty() {
                rows.push(vec!["Number".into(), l.luminaire_number.trim().into()]);
            }
            let mount = match p.mounting_hint() {
                MountingHint::Wall => "wall".to_string(),
                MountingHint::Ceiling => "ceiling".to_string(),
                MountingHint::WallOrCeiling => "wall or ceiling".to_string(),
                MountingHint::Other(n) => format!("code {n}"),
            };
            rows.push(vec!["Mounting".into(), mount]);
            rows.push(vec![
                "Data".into(),
                format!(
                    "{} C-planes × {} γ angles, γ up to {:.0}°, largest range {:.2} m",
                    l.num_c_planes,
                    l.num_g_planes,
                    l.g_angles.last().copied().unwrap_or(0.0),
                    l.intensities.iter().flatten().copied().fold(0.0, f64::max)
                ),
            ]);
            for m in Motion::ALL {
                match (p.scale(m), v.motion_depth_limit(m)) {
                    (Some(k), Some(d)) => rows.push(vec![
                        m.label().to_string(),
                        format!("volume × {k}, detected down to {d:.2} m below the sensor"),
                    ]),
                    _ => rows.push(vec![m.label().to_string(), "no data".into()]),
                }
            }
            let raw: Vec<String> = p.raw.iter().map(|x| format!("{x}")).collect();
            rows.push(vec!["Parameter block".into(), raw.join(", ")]);
        }
        SensorSource::Xml(x) => {
            let hd = &x.header;
            for (k, v) in [
                ("Manufacturer", &hd.manufacturer),
                ("Product", &hd.product_name),
                ("Number", &hd.product_number),
                ("Technology", &hd.product_technology),
                ("Laboratory", &hd.laboratory),
                ("Report", &hd.report_number),
                ("Report date", &hd.report_date),
            ] {
                if let Some(v) = v {
                    rows.push(vec![k.to_string(), v.clone()]);
                }
            }
            if let Some(mt) = x.sensor.measurement_type.clone() {
                rows.push(vec!["Measurement".into(), mt]);
            }
            if let Some(mt) = x.sensor.mounting_type {
                let mount = match mt {
                    1 => "wall",
                    2 => "ceiling",
                    3 => "wall or ceiling",
                    _ => "other",
                };
                rows.push(vec!["Mounting".into(), mount.into()]);
            }
            if let Some(p) = x.sensor.total_system_power {
                rows.push(vec!["System power".into(), format!("{p} W")]);
            }
            rows.push(vec![
                "SensXML version".into(),
                x.version.clone().unwrap_or_default(),
            ]);
            for m in Motion::ALL {
                let hs: Vec<String> = x.heights(m).iter().map(|h| format!("{h} m")).collect();
                rows.push(vec![
                    m.label().to_string(),
                    if hs.is_empty() {
                        "no data".into()
                    } else {
                        format!("measured at {}", hs.join(", "))
                    },
                ]);
            }
            for w in &x.warnings {
                rows.push(vec!["Note from the file".into(), w.clone()]);
            }
        }
    }
    s.push_str(&table("(auto, 1fr)", &["Field", "Value"], &rows));

    // 2. Detection areas at the chosen height
    let height_text = match src {
        SensorSource::Ldt(_) => format!("{h:.2} m below the sensor"),
        SensorSource::Xml(_) => format!("mounting height {h:.2} m"),
    };
    s.push_str(&format!("\n= Detection areas, {}\n", esc(&height_text)));
    // plan and its table stay on one page
    s.push_str("#block(breakable: false)[\n");
    let mut traces = Vec::new();
    let mut rows = Vec::new();
    for (i, m) in Motion::ALL.iter().enumerate() {
        match footprint(src, *m, h, opt.planning) {
            Some((fp, q)) if !fp.is_empty() => {
                rows.push(vec![
                    m.label().to_string(),
                    format!("{:.2} m{}", fp.max_range, quality_mark(q)),
                    format!("{:.1} m²", fp.area_m2),
                    format!("{:.2} m", fp.equivalent_diameter()),
                ]);
                traces.push(SensorPlanTrace {
                    label: m.label().to_string(),
                    color: TRACE_COLORS[i].to_string(),
                    footprint: fp,
                });
            }
            Some(_) => rows.push(vec![
                m.label().to_string(),
                "not detected at this height".into(),
                "–".into(),
                "–".into(),
            ]),
            None => rows.push(vec![
                m.label().to_string(),
                "no data".into(),
                "–".into(),
                "–".into(),
            ]),
        }
    }
    if traces.is_empty() {
        s.push_str("Nothing is detected at this height.\n\n");
    } else {
        s.push_str(&image(&SensorPlanSvg::render(&traces, 520.0, &theme), 46));
    }
    s.push_str(&table(
        "(1fr, auto, auto, auto)",
        &["Movement", "Max range", "Area", "Ø equivalent"],
        &rows,
    ));
    if matches!(src, SensorSource::Xml(_)) {
        s.push_str(&format!(
            "#text(size: 8pt, fill: gray)[{} (i) interpolated between measured heights, (e) outside the measured heights.]\n",
            if opt.planning {
                "Idealised planning shapes."
            } else {
                "Measured data."
            }
        ));
    }
    s.push_str("]\n");

    // 3. Over the mounting height
    let heights: Vec<f64> = match src {
        SensorSource::Ldt(_) => vec![1.5, 2.0, 2.5, 3.0, 3.5, 4.0, 5.0, 6.0, 8.0],
        SensorSource::Xml(x) => {
            let mut hs: Vec<f64> = vec![2.0, 2.5, 3.0, 4.0];
            for m in Motion::ALL {
                hs.extend(x.heights(m));
            }
            hs.sort_by(|a, b| a.partial_cmp(b).unwrap_or(core::cmp::Ordering::Equal));
            hs.dedup_by(|a, b| (*a - *b).abs() < 1e-6);
            hs
        }
    };
    s.push_str("\n= Detection areas over the height\n");
    s.push_str(match src {
        SensorSource::Ldt(_) => "Max range and area per movement for planes at several depths below the sensor (mounting height minus the height of the person).\n\n",
        SensorSource::Xml(_) => "Max range and area per movement and mounting height.\n\n",
    });
    let motions: Vec<Motion> = Motion::ALL
        .iter()
        .copied()
        .filter(|m| match src {
            SensorSource::Ldt(v) => v.params().scale(*m).is_some(),
            SensorSource::Xml(x) => !x.heights(*m).is_empty(),
        })
        .collect();
    let mut rows = Vec::new();
    for hh in &heights {
        let mut r = vec![format!("{hh:.2} m")];
        for m in &motions {
            r.push(match footprint(src, *m, *hh, opt.planning) {
                Some((fp, q)) if !fp.is_empty() => format!(
                    "{:.2} m · {:.0} m²{}",
                    fp.max_range,
                    fp.area_m2,
                    quality_mark(q)
                ),
                Some(_) => "not detected".into(),
                None => "–".into(),
            });
        }
        rows.push(r);
    }
    let first = match src {
        SensorSource::Ldt(_) => "Below sensor",
        SensorSource::Xml(_) => "Mounting height",
    };
    let header: Vec<&str> = std::iter::once(first)
        .chain(motions.iter().map(|m| m.label()))
        .collect();
    let columns = format!("(auto, {})", vec!["1fr"; motions.len()].join(", "));
    s.push_str(&table(&columns, &header, &rows));

    // 4. Detection volume
    let volume = match src {
        SensorSource::Ldt(v) => Some(((*v).clone(), false)),
        SensorSource::Xml(x) => x
            .to_detection_volume(Motion::Tangential, opt.planning)
            .map(|v| (v, true)),
    };
    if let Some((v, derived)) = volume {
        s.push_str("\n#pagebreak(weak: true)\n= Detection volume\n");
        if derived {
            let hs: Vec<String> = match src {
                SensorSource::Xml(x) => x
                    .heights(Motion::Tangential)
                    .iter()
                    .map(|h| format!("{h} m"))
                    .collect(),
                _ => Vec::new(),
            };
            s.push_str(&format!(
                "Tangential walking. The volume is rebuilt from the measured heights ({}); between them the areas are interpolated, below the deepest height nothing is known.\n\n",
                esc(&hs.join(", "))
            ));
        } else {
            s.push_str("The values of a sensor LDT are distances in metres from the sensor to the edge of the detection volume, for every direction. These views show that volume.\n\n");
        }
        s.push_str("#grid(columns: (1fr, 1fr), gutter: 8pt,\n");
        s.push_str(&format!(
            "  [{}],\n  [{}])\n",
            image(
                &diagrams::render(&v, SensorDiagram::Polar, 420.0, 420.0, h, &theme),
                100
            )
            .trim_end(),
            image(
                &diagrams::render(&v, SensorDiagram::Volume3d, 460.0, 380.0, h, &theme),
                100
            )
            .trim_end()
        ));
        s.push_str(&image(
            &diagrams::render(&v, SensorDiagram::Heatmap, 620.0, 380.0, h, &theme),
            80,
        ));
    }

    // 5. Method
    s.push_str(
        r##"
= How to read this report
- *Tangential walking*: walking across the sensor's view; the largest area.
- *Radial walking*: walking towards the sensor.
- *Presence (seated)*: small movements at a desk; the smallest area.
- A sensor LDT stores the detection volume: for each direction (C, γ) the distance in metres to its edge. The detection area at a mounting height is the cut through that volume at the depth "mounting height minus the height of the person". Radial and presence areas are the same volume scaled by the factors in the file's parameter block.
- A SensXML file stores measured detection areas at a few mounting heights; between them they are interpolated, below the lowest they shrink in proportion to the height, above the highest they are held.
- Views based on light (cone, beam angle, isolux, glare) do not apply to sensors.
- The reference height for comparing sensors is 2.0 m.
"##,
    );
    s
}

/// Move every Typst heading down by `levels` (`= A` → `== A`).
fn shift_headings(body: &str, levels: usize) -> String {
    let extra = "=".repeat(levels);
    body.lines()
        .map(|l| {
            let eq = l.chars().take_while(|c| *c == '=').count();
            if eq > 0 && l[eq..].starts_with(' ') {
                format!("{extra}{l}")
            } else {
                l.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n"
}

fn kind_label(src: &SensorSource) -> &'static str {
    match src {
        SensorSource::Ldt(_) => "Sensor LDT (detection volume)",
        SensorSource::Xml(_) => "SensXML (detection areas per mounting height)",
    }
}

/// Append a "Sensors" chapter to a photometric report (the Typst source of
/// `generate_typst_with_files`): one subsection per sensor, same content as
/// the stand-alone sensor report. The report's outline picks it up.
pub fn append_sensor_chapter(
    photometric: &str,
    sensors: &[(SensorSource, SensorReportOptions)],
) -> String {
    let mut s = String::from(photometric);
    if sensors.is_empty() {
        return s;
    }
    s.push_str("\n#pagebreak(weak: true)\n= Sensors\n");
    for (src, opt) in sensors {
        s.push_str(&format!(
            "\n== {}\n#text(size: 9pt, fill: gray)[{}]\n",
            esc(&opt.name),
            kind_label(src)
        ));
        if opt.demo {
            s.push_str("#text(fill: rgb(\"#b45309\"))[Synthetic demo data, not a product.]\n");
        }
        s.push_str(&shift_headings(&report_body(src, opt), 2));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    const LDT: &str = include_str!("../../eulumdat/tests/fixtures/sensors/demo_ceiling_360.ldt");
    const XML: &[u8] =
        include_bytes!("../../eulumdat/tests/fixtures/sensors/demo_highbay_sensxml.xml");

    #[test]
    fn ldt_report_has_sections_and_numbers() {
        let v = DetectionVolume::new(eulumdat::Eulumdat::parse(LDT).unwrap());
        let opt = SensorReportOptions {
            name: "Demo ceiling".into(),
            demo: true,
            ..Default::default()
        };
        let s = generate_sensor_report(&SensorSource::Ldt(&v), &opt);
        for want in [
            "= Summary",
            "= Detection areas",
            "= Detection areas over the height",
            "= Detection volume",
            "8.00 m",
            "Synthetic demo data",
            "#image(bytes(",
        ] {
            assert!(s.contains(want), "missing {want}");
        }
        assert!(!s.contains("Relux"));
    }

    #[test]
    fn chapter_appends_to_a_photometric_report() {
        let v = DetectionVolume::new(eulumdat::Eulumdat::parse(LDT).unwrap());
        let lum = eulumdat::Eulumdat::parse(LDT).unwrap();
        let (photometric, _) =
            crate::generate_typst_with_files(&lum, &crate::ReportOptions::default().sections);
        let opt = SensorReportOptions {
            name: "Ceiling sensor".into(),
            ..Default::default()
        };
        let s = append_sensor_chapter(&photometric, &[(SensorSource::Ldt(&v), opt)]);
        assert!(s.starts_with(&photometric));
        assert!(s.contains("\n= Sensors\n"));
        assert!(s.contains("\n== Ceiling sensor\n"));
        assert!(
            s.contains("\n=== Summary\n"),
            "headings shifted under the sensor"
        );
        assert!(
            !s[photometric.len()..].contains("#set page"),
            "no second preamble"
        );
    }

    /// `SENSOR_CHAPTER_OUT=out.typ cargo test -p eulumdat-typst write_combined`
    /// writes a photometric report with a sensor chapter for a typst check.
    #[test]
    fn write_combined() {
        let Ok(out) = std::env::var("SENSOR_CHAPTER_OUT") else {
            return;
        };
        let lum = eulumdat::Eulumdat::parse(LDT).unwrap();
        let (photometric, _) =
            crate::generate_typst_with_files(&lum, &crate::ReportOptions::default().sections);
        let x = SensXml::parse(XML).unwrap();
        let opt = SensorReportOptions {
            name: "High-bay sensor".into(),
            height: 8.0,
            demo: true,
            ..Default::default()
        };
        let s = append_sensor_chapter(&photometric, &[(SensorSource::Xml(&x), opt)]);
        std::fs::write(out, s).unwrap();
    }

    #[test]
    fn sensxml_report_marks_interpolation() {
        let x = SensXml::parse(XML).unwrap();
        let opt = SensorReportOptions {
            name: "High-bay".into(),
            height: 8.0,
            planning: true,
            ..Default::default()
        };
        let s = generate_sensor_report(&SensorSource::Xml(&x), &opt);
        assert!(s.contains("mounting height 8.00 m"));
        assert!(s.contains("(i)"), "interpolated mark");
        assert!(s.contains("rebuilt from the measured heights"));
    }
}
